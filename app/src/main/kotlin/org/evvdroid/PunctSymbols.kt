	/** The entry for [codepoint], or null. Binary search: the table is sorted. */
	fun lookup(codepoint: Int): Entry? {
		var lo = 0
		var hi = ENTRIES.size - 1
		while (lo <= hi) {
			val mid = (lo + hi) / 2
			val at = ENTRIES[mid].codepoint
			if (at == codepoint) return ENTRIES[mid]
			if (at < codepoint) lo = mid + 1 else hi = mid - 1
		}
		return null
	}
